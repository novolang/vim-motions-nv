-- gen.lua — run key vectors in a real editor and write the expected results.
--
-- Usage, from the package directory:
--
--   nvim --headless --clean -l tests/oracle/gen.lua tests/oracle/<area>.lua tests/<area>_tests.nv
--
-- The vectors file returns a list of cases.  A case is
--
--   { name = "...", text = { "line", ... }, at = { line, col }, keys = "...",
--     top = 0, nocursor = false }
--
-- with line and col counted from zero and col counted in characters.  The
-- keys are in the notation of `:help key-notation`.  Each case is run by
-- one.lua in an editor of its own, and the lines, the cursor, the mode, the
-- Visual anchor, the first line shown and the registers that follow are
-- written as a test.  A case is one string of fields, so that the formatter
-- leaves it alone.

local here = debug.getinfo(1, "S").source:sub(2):match("(.*/)") or "./"

local FIELD = "\30"
local REGISTER = "\31"

local function escape(s)
  local out = { '"' }
  for i = 1, #s do
    local c = s:sub(i, i)
    local b = c:byte()
    if c == "\\" then
      out[#out + 1] = "\\\\"
    elseif c == '"' then
      out[#out + 1] = '\\"'
    elseif c == "$" then
      out[#out + 1] = "\\$"
    elseif c == "\n" then
      out[#out + 1] = "\\n"
    elseif c == "\t" then
      out[#out + 1] = "\\t"
    elseif b < 32 or b == 127 then
      out[#out + 1] = string.format("\\x%02x", b)
    else
      out[#out + 1] = c
    end
  end
  out[#out + 1] = '"'
  return table.concat(out)
end

local function slug(name)
  local s = name:lower():gsub("[^%w]+", "_"):gsub("^_+", ""):gsub("_+$", "")
  return s:sub(1, 48)
end

local cases = dofile(arg[1])
local area = arg[1]:match("([%w_]+)%.lua$")

local unique, names = {}, {}
for _, c in ipairs(cases) do
  if not names[c.name] then
    names[c.name] = true
    unique[#unique + 1] = c
  end
end

-- Run the cases, a batch of editors at a time.
local tmp = vim.fn.tempname()
vim.fn.mkdir(tmp, "p")
local results = {}
local batch = 12
local i = 1
while i <= #unique do
  local procs = {}
  for k = i, math.min(i + batch - 1, #unique) do
    local inp = string.format("%s/%d.in.json", tmp, k)
    local outp = string.format("%s/%d.out.json", tmp, k)
    local f = assert(io.open(inp, "w"))
    f:write(vim.json.encode(unique[k]))
    f:close()
    procs[k] = {
      outp = outp,
      p = vim.system({ vim.v.progpath, "--headless", "--clean", "-l", here .. "one.lua", inp, outp }, { text = true }),
    }
  end
  for k, pr in pairs(procs) do
    pr.p:wait()
    local f = assert(io.open(pr.outp, "r"), "no result for case " .. unique[k].name)
    results[k] = vim.json.decode(f:read("*a"))
    f:close()
    assert(not results[k].error, results[k].error)
  end
  i = i + batch
end

local out = {}
local function w(s)
  out[#out + 1] = s
end

w("// " .. area .. "_tests.nv — vectors checked against a real editor.")
w("//")
w("// Generated by tests/oracle/gen.lua from tests/oracle/" .. area .. ".lua.  Each")
w("// case types keys against a text and compares the lines, the cursor, the")
w("// mode, the Visual anchor, the first line shown and the registers with")
w("// what the editor produced for the same keys.  A case is one string of")
w("// fields; a cursor of -1 is not compared.")
w("")
w("use std.test")
w("use std.list")
w("use std.str")
w("use vimmodal")
w("use vimstep")
w("use vimram")
w("")
w("fn num(s: Str) -> Int")
w("    str.to_int(s) ?? 0")
w("")
w("// text_of reads the lines of a text.  \"#n\" is n lines of the form \"  line 1\".")
w("fn text_of(s: Str) -> [Str]")
w("    if str.starts_with(s, \"#\")")
w("        var out: [Str] = []")
w("        for i in 1..=num(str.slice(s, 1, str.len(s)))")
w("            list.push(out, \"  line ${i}\")")
w("        return out")
w("    str.split(s, \"\\n\")")
w("")
w("fn vector(spec: Str) [io]")
w("    let f = str.split(spec, \"\\x1e\")")
w("    test.case(f[0])")
w("    let text = text_of(f[1])")
w("    var d = vimram.doc_new(text, 22)")
w("    d.top = num(f[4])")
w("    var m = vimmodal.modal_new()")
w("    m = vimstep.set_cursor(m, d, num(f[2]), num(f[3]))")
w("    m = vimram.run(var d, m, f[5])")
w("    let wl = num(f[7])")
w("    let wanl = num(f[10])")
w("    let wtop = num(f[12])")
w("    let names = ['\"', '0', '1', '-', 'a', 'b']")
w("    var gt: [Str] = []")
w("    var gw: [Bool] = []")
w("    for n in names")
w("        list.push(gt, m.reg_text(n))")
w("        list.push(gw, m.reg_is_linewise(n))")
w("    let ls = vimram.doc_lines(d)")
w("    let want = if f[6] == \"=\" then text else text_of(f[6])")
w("    let same = ls == want")
w("    var rt = str.split(f[13], \"\\x1f\")")
w("    var rl: [Bool] = []")
w("    for ch in str.chars(f[14])")
w("        list.push(rl, ch == \"t\")")
w("    if f[13] == \"\"")
w("        rt = [\"\", \"\", \"\", \"\", \"\", \"\"]")
w("        rl = [false, false, false, false, false, false]")
w("    let got = summary(if same then [\"=\"] else ls, if wl >= 0 then m.line else -1, if wl >= 0 then m.col else -1, m.mode, if wanl >= 0 then m.anchor_line else -1, if wanl >= 0 then m.anchor_col else -1, if wtop >= 0 then d.top else -1, gt, gw)")
w("    let exp = summary(if same then [\"=\"] else want, wl, num(f[8]), num(f[9]), wanl, num(f[11]), wtop, rt, rl)")
w("    test.assert_eq_str(got, exp)")
w("")
w("fn summary(lines: [Str], l: Int, c: Int, mode: Int, anl: Int, anc: Int, top: Int, rt: [Str], rl: [Bool]) -> Str")
w("    var s = \"lines=${lines} cursor=${l},${c} mode=${mode} anchor=${anl},${anc} top=${top} registers=\"")
w("    for i in 0..list.len(rt)")
w("        s = s + \"[${rt[i]}:${rl[i]}]\"")
w("    s")
w("")

for n, c in ipairs(unique) do
  local r = results[n]
  local wl, wc = r.line, r.col
  if c.nocursor then
    wl, wc = -1, -1
  end
  local wtop = -1
  if c.top ~= nil or c.scroll then
    wtop = r.top
  end
  local rt, rl = {}, {}
  local any = false
  for k = 1, #r.rt do
    rt[k] = r.rt[k]
    rl[k] = r.rl[k] and "t" or "f"
    if r.rt[k] ~= "" or r.rl[k] then
      any = true
    end
  end
  local function pack(lines)
    local numbered = #lines >= 10
    for k, l in ipairs(lines) do
      if l ~= "  line " .. k then
        numbered = false
        break
      end
    end
    if numbered then
      return "#" .. #lines
    end
    return table.concat(lines, "\n")
  end
  local text_field = pack(c.text)
  local want_field = pack(r.lines)
  if want_field == text_field then
    want_field = "="
  end
  local fields = {
    c.name,
    text_field,
    tostring(c.at[1]),
    tostring(c.at[2]),
    tostring(c.top or 0),
    c.keys,
    want_field,
    tostring(wl),
    tostring(wc),
    tostring(r.mode),
    tostring(r.anl),
    tostring(r.anc),
    tostring(wtop),
    any and table.concat(rt, REGISTER) or "",
    any and table.concat(rl) or "",
  }
  w("@test")
  w(string.format("fn t%d() [io]", n))
  w("    vector(" .. escape(table.concat(fields, FIELD)) .. ")")
  w("")
end

local f = assert(io.open(arg[2], "w"))
f:write(table.concat(out, "\n"))
f:close()
vim.fn.delete(tmp, "rf")
vim.cmd("qa!")
